// Strict ClarifyDSL -> Elsa code-first adapter for the approved OrderApproval slice.
// This intentionally fails on unsupported nodes. A successful generated C# build
// proves we are using Elsa runtime activities, not the homemade WorkflowRunner.
import {compileElsaManifest} from "./elsa-manifest.mjs";
import {readFileSync,writeFileSync} from "node:fs";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";

const handlers = new Map([
  ["ValidateOrder", "ValidateOrder"],
  ["ReserveInventory", "ReserveInventory"],
  ["PublishOrder", "PublishOrder"]
]);
export function emitElsaWorkflow(source) {
  const manifest=compileElsaManifest(source,[...handlers.keys()]);
  if(manifest.id!=="OrderApproval"||manifest.version!==1)
    throw Error("Only the published OrderApproval v1 slice is supported");
  const statements=[];
  for(const [i,step] of manifest.steps.entries()){
    if(step.type==="registered-csharp-activity") {
      if(!handlers.has(step.activity))throw Error("Unregistered C# activity "+step.activity);
      // Demo handlers are deliberately identifiable and side-effect-free.
      statements.push('new WriteLine("Clarify activity: '+handlers.get(step.activity)+'")');
    } else if(step.type==="human-approval-bookmark") {
      if(step.activity!=="Approval"||step.role!=="Manager")throw Error("Only Manager Approval is supported");
      // This references our genuine Elsa bookmark activity.
      statements.push('new WaitForManagerApproval { OrderCorrelation = new("order:demo") }');
    } else throw Error("Elsa adapter does not support: "+step.type);
  }
  return `// <auto-generated> From OrderApproval.clarify. Do not edit by hand. </auto-generated>
using Elsa.Workflows;
using Elsa.Workflows.Activities;
using Clarify.Examples.Elsa;

namespace Clarify.Examples.Elsa;

/// <summary>
/// A generated code-first Elsa approval workflow. Durable execution requires
/// Elsa runtime persistence in the host; sample activities are illustrative.
/// </summary>
public sealed class GeneratedOrderApprovalWorkflow : WorkflowBase
{
    /// <summary>Constructs the generated Elsa activity graph.</summary>
    /// <param name="builder">Workflow builder supplied by Elsa.</param>
    protected override void Build(IWorkflowBuilder builder)
    {
        builder.Root = new Sequence
        {
            Activities =
            {
                ${statements.join(",\n                ")}
            }
        };
    }
}
`;
}
const own=fileURLToPath(import.meta.url);
if(process.argv[1] && resolve(process.argv[1])===own){
  const root=resolve(dirname(own),"..");
  const source=readFileSync(resolve(root,"examples/workflows/OrderApproval.clarify"),"utf8");
  const output=resolve(root,"tests/Clarify.Elsa.Approval/GeneratedOrderApprovalWorkflow.cs");
  writeFileSync(output,emitElsaWorkflow(source));
  console.log("Generated Elsa workflow: "+output);
}
