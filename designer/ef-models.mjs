// Clarify dictionary -> EF Core model generator (first executable relational slice).
// This deliberately generates SOURCE only. It never connects to a database or
// invokes EF migrations. All entities require explicit, typed primary keys.
import {analyzeDependencies} from './dependencies.mjs';

const ident=/^[A-Za-z_][A-Za-z0-9_]*$/;
const scalar={string:'string',int:'int',long:'long',decimal:'decimal',bool:'bool',date:'DateOnly'};
const esc=s=>String(s).replaceAll('\\','\\\\').replaceAll('"','\\"');
const storage=(model,e)=>e.database||model.defaultDatabase||'default';
const toClass=id=>id.split(/[_-]/).map(x=>x[0].toUpperCase()+x.slice(1)).join('');
const nullable=f=>f.required||f.primaryKey?'':'?';
function column(f){
 if(!scalar[f.type])throw Error('Unsupported generated field type '+f.type+' for '+f.name+'; use typed mapping generator before release');
 return '    /// <summary>Dictionary field '+f.name+' ('+f.type+').</summary>\\n    public '+scalar[f.type]+nullable(f)+' '+f.name+' { get; set; }'+(f.type==='string'&&f.required?' = "";':'');
}
export function generateEfModels(dictionary){
 const analysis=analyzeDependencies(dictionary);
 if(analysis.errors.length)throw Error('Invalid dictionary: '+analysis.errors.join('; '));
 const entities=dictionary.entities||[],names=new Set(),result=[];
 for(const entity of entities){
  if(!ident.test(entity.name)||names.has(entity.name))throw Error('Invalid or duplicate entity '+entity.name);
  names.add(entity.name);
  const fields=entity.fields||[];
  const keys=fields.filter(f=>f.primaryKey);
  if(keys.length!==1)throw Error('Entity '+entity.name+' requires exactly one explicit primary key in this generator');
  if(!['int','long','string'].includes(keys[0].type))throw Error('Unsupported key type '+keys[0].type);
  const fieldNames=new Set();
  for(const f of fields){
   if(f.unique!==undefined && typeof f.unique!=='boolean')throw Error('unique must be boolean on '+entity.name+'.'+f.name);
   if(f.unique===true && f.primaryKey)throw Error('Primary key is already unique: '+entity.name+'.'+f.name);
   if(!ident.test(f.name)||fieldNames.has(f.name))throw Error('Invalid or duplicate field '+entity.name+'.'+f.name);
   fieldNames.add(f.name);
  }
 }
 // Each independent connection gets its own context. Never emit an EF FK
 // spanning two contexts; cross-db references remain application-managed.
 for(const db of analysis.databases){
  if(!ident.test(db))throw Error('Database ID must be C# identifier: '+db);
  const scoped=entities.filter(e=>storage(dictionary,e)===db);
  const className=toClass(db)+'DbContext';
  const lines=[
   '// <auto-generated> Generated by Clarify. User code belongs in separate files. </auto-generated>',
   'using System;','using Microsoft.EntityFrameworkCore;',
   'namespace Clarify.Generated;',
   ''
  ];
  for(const e of scoped){
   lines.push('/// <summary>Dictionary-owned entity '+e.name+'.</summary>');
   lines.push('public sealed class '+e.name+' {');
   for(const f of e.fields)lines.push(column(f));
   lines.push('}','');
  }
  lines.push('/// <summary>EF Core context for logical database '+db+'.</summary>');
  lines.push('public sealed class '+className+'(DbContextOptions<'+className+'> options) : DbContext(options) {');
  for(const e of scoped){lines.push('    /// <summary>Query and update '+e.name+' records.</summary>');lines.push('    public DbSet<'+e.name+'> '+e.name+'Rows => Set<'+e.name+'>();');}
  lines.push('    /// <summary>Configures generated keys, columns and relationships.</summary>');
  lines.push('    /// <param name="model">EF Core model builder.</param>');
  lines.push('    protected override void OnModelCreating(ModelBuilder model) {');
  for(const e of scoped){
   const pk=e.fields.find(f=>f.primaryKey);
   lines.push('        model.Entity<'+e.name+'>().ToTable("'+e.name+'").HasKey(x => x.'+pk.name+');');
   for(const f of e.fields){
    if(f.type==='string'&&f.required)lines.push('        model.Entity<'+e.name+'>().Property(x => x.'+f.name+').IsRequired();');
    if(f.maxLength!==undefined){
     if(f.type!=='string'||!Number.isInteger(f.maxLength)||f.maxLength<1||f.maxLength>100000)
      throw Error('Invalid maxLength on '+e.name+'.'+f.name);
     lines.push('        model.Entity<'+e.name+'>().Property(x => x.'+f.name+').HasMaxLength('+f.maxLength+');');
    }
    if(f.type==='decimal')lines.push('        model.Entity<'+e.name+'>().Property(x => x.'+f.name+').HasPrecision(19,4);');
    if(f.unique===true)lines.push('        model.Entity<'+e.name+'>().HasIndex(x => x.'+f.name+').IsUnique();');
   }
  }
  for(const r of dictionary.relationships||[]){
   const child=entities.find(e=>e.name===r.from),parent=entities.find(e=>e.name===r.to);
   if(storage(dictionary,child)!==db)continue;
   if(storage(dictionary,parent)!==db)continue; // external: no EF FK
   if(r.kind==='external')continue; // explicitly application-managed
   const pk=parent.fields.find(f=>f.primaryKey);
   if(!pk || (r.principalKey||'Id')!==pk.name)throw Error('Unsupported principal key for '+r.from+' -> '+r.to);
   const fk=child.fields.find(f=>f.name===r.foreignKey);
   if(!fk || fk.type!==pk.type)throw Error('Foreign key type mismatch: '+r.from+'.'+r.foreignKey);
   if(r.onDelete==='set-null'&&fk.required)throw Error('set-null requires nullable FK: '+r.from+'.'+r.foreignKey);
   const behavior={restrict:'Restrict',cascade:'Cascade','set-null':'SetNull'}[r.onDelete];
   if(!behavior)throw Error('Invalid delete behavior');
   const builder='model.Entity<'+child.name+'>().HasOne<'+parent.name+'>()'+(r.cardinality==='one-to-one'?'.WithOne()':'.WithMany()')+'.HasForeignKey<'+child.name+'>(x => x.'+r.foreignKey+')';
   lines.push('        '+builder+'.OnDelete(DeleteBehavior.'+behavior+');');
   lines.push('        model.Entity<'+child.name+'>().HasIndex(x => x.'+r.foreignKey+')'+(r.cardinality==='one-to-one'?'.IsUnique()':'')+';');
  }
  lines.push('    }','}','');
  result.push({database:db,path:'generated/'+className+'.g.cs',source:lines.join('\\n').replaceAll('\\n','\n')});
 }
 return {files:result,warnings:analysis.warnings};
}

