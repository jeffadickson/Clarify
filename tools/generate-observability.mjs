// Generates the observability bootstrap with every Clarify application.
// No telemetry server is required. Instrumentation and export configuration
// are deliberately separate: tracing can run even with no OTLP destination.
import {readFileSync,writeFileSync} from "node:fs";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";

export function generateObservabilityRegistration(dictionary, appName="OrderEntry") {
  if(!Array.isArray(dictionary?.entities)||dictionary.entities.length===0)
    throw Error("A valid Clarify dictionary is required.");
  if(!/^[A-Za-z][A-Za-z0-9_]*$/.test(appName))throw Error("Invalid application name");
  return `// <auto-generated> Clarify observability bootstrap. Do not edit. </auto-generated>
using Clarify.Observability;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;

namespace Clarify.Demo.Web;

/// <summary>
/// Every generated application registers tracing and metrics automatically.
/// With no OTLP destination this has no network export dependency.
/// </summary>
public static class GeneratedObservability
{
    public const string ApplicationName = "${appName}";
    public static IServiceCollection AddGeneratedObservability(
        this IServiceCollection services, IConfiguration configuration)
        => services.AddClarifyObservability(configuration);
}
`;
}
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const dictionary=JSON.parse(readFileSync(resolve(root,"examples/order-entry/dictionary.json"),"utf8"));
 const dest=resolve(root,"src/Clarify.Demo.Web/GeneratedObservability.cs");
 writeFileSync(dest,generateObservabilityRegistration(dictionary),"utf8");
 console.log("Generated observability bootstrap: "+dest);
}
