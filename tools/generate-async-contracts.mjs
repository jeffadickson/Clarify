import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
// Generator-owned contracts: developers implement custom behavior in separate C# files.
export function generateAsyncContracts(dictionary) {
 const names=new Set();
 const lines=['// <auto-generated> Clarify async browse contracts. </auto-generated>',
 'using System.Collections.Generic;','using System.Threading;','using System.Threading.Tasks;',
 'namespace Clarify.Generated;',
 '/// <summary>A bounded page of records and whether another page exists.</summary>',
 '/// <typeparam name="T">Entity model type.</typeparam>',
 '/// <param name="Items">Records in this page.</param>',
 '/// <param name="Page">Zero-based page index.</param>',
 '/// <param name="PageSize">Maximum records per page.</param>',
 '/// <param name="HasNext">Whether additional records exist.</param>',
 'public sealed record BrowsePage<T>(IReadOnlyList<T> Items, int Page, int PageSize, bool HasNext);'];
 for(const e of dictionary.entities||[]){
  if(!/^[A-Za-z_][A-Za-z0-9_]*$/.test(e.name)||names.has(e.name))throw Error('Invalid entity name');
  names.add(e.name);
  lines.push('/// <summary>Cancellation-aware browse for '+e.name+'.</summary>');
  lines.push('public interface I'+e.name+'AsyncBrowse {');
  lines.push('    /// <summary>Retrieves a bounded, cancellation-aware page of '+e.name+' records.</summary>');
  lines.push('    /// <param name="page">Zero-based page number.</param>');
  lines.push('    /// <param name="pageSize">Maximum number of records.</param>');
  lines.push('    /// <param name="ct">Cancellation token.</param>');
  lines.push('    /// <returns>Page results and continuation indicator.</returns>');
  lines.push('    Task<BrowsePage<'+e.name+'Model>> PageAsync(int page, int pageSize, CancellationToken ct = default);');
  lines.push('}');
 }
 return lines.join('\n')+'\n';
}
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const d=JSON.parse(readFileSync(resolve(root,'examples/order-entry/dictionary.json'),'utf8'));
 const target=resolve(root,'examples/generated/AsyncStores.g.cs');
 writeFileSync(target,generateAsyncContracts(d));
 console.log('Generated '+target);
}